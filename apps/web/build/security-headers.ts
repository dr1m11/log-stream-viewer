import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import type { Plugin } from 'vite';

import { resolveStreamUrl } from '../src/shared/config/stream-url.ts';

/** One block of a Cloudflare `_headers` file: a path pattern and the headers it adds. */
export interface HeaderRule {
  /** An absolute path; `*` is a splat that matches any characters, including `/`. */
  readonly path: string;
  readonly headers: readonly (readonly [name: string, value: string])[];
}

export const HEADERS_FILE = '_headers';

/**
 * The page's Content Security Policy: everything from the app's own origin, plus WebSocket
 * connections to the stream's origin. No inline scripts or styles: the pre-paint theme script is
 * an external file, and React applies `style` props through the CSSOM, which CSP allows.
 */
export function contentSecurityPolicy(streamUrl: string): string {
  const { protocol, host, hostname } = new URL(streamUrl);
  // CSP host sources have no syntax for IP literals in brackets.
  if (hostname.startsWith('[')) {
    throw new Error(
      `VITE_STREAM_URL must name a host, not an IPv6 address, so the CSP can allow it; got ${JSON.stringify(streamUrl)}`,
    );
  }
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self'",
    `connect-src 'self' ${protocol}//${host}`,
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** Response headers of the deployed app (Cloudflare) and of `vite preview`. */
export function securityHeaderRules(streamUrl: string): HeaderRule[] {
  return [
    {
      path: '/*',
      headers: [
        ['Content-Security-Policy', contentSecurityPolicy(streamUrl)],
        ['X-Content-Type-Options', 'nosniff'],
        ['X-Frame-Options', 'DENY'],
        ['Referrer-Policy', 'strict-origin-when-cross-origin'],
        ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=()'],
        ['Cross-Origin-Opener-Policy', 'same-origin'],
      ],
    },
    // Vite puts a content hash in every file name under /assets.
    { path: '/assets/*', headers: [['Cache-Control', 'public, max-age=31536000, immutable']] },
  ];
}

export function formatHeadersFile(rules: readonly HeaderRule[]): string {
  const blocks = rules.map((rule) =>
    [rule.path, ...rule.headers.map(([name, value]) => `  ${name}: ${value}`)].join('\n'),
  );
  return [
    '# Generated by apps/web/build/security-headers.ts from VITE_STREAM_URL. Cloudflare Workers',
    '# static assets apply it (https://developers.cloudflare.com/workers/static-assets/headers/),',
    '# and `vite preview` serves the same headers.',
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n');
}

/**
 * Parses the subset of the `_headers` syntax that {@link formatHeadersFile} writes: comments,
 * path patterns with `*` splats and `Name: value` lines. Anything else (placeholders, absolute
 * URLs, `! Name` removals) throws, so preview never silently differs from Cloudflare.
 */
export function parseHeadersFile(text: string): HeaderRule[] {
  const rules: { path: string; headers: [string, string][] }[] = [];
  for (const [index, line] of text.split(/\r?\n/).entries()) {
    const content = line.trim();
    if (content === '' || content.startsWith('#')) continue;
    const where = `${HEADERS_FILE} line ${String(index + 1)}`;

    if (!/^\s/.test(line)) {
      // Cloudflare allows one splat per pattern and drops rules with more.
      if (!content.startsWith('/') || content.includes(':') || content.split('*').length > 2) {
        throw new Error(
          `${where}: expected a path pattern with at most one * such as /assets/*, got ${JSON.stringify(content)}`,
        );
      }
      rules.push({ path: content, headers: [] });
      continue;
    }

    const rule = rules.at(-1);
    const colon = content.indexOf(':');
    if (rule === undefined || colon <= 0 || content.startsWith('!')) {
      throw new Error(
        `${where}: expected an indented "Name: value" under a path, got ${JSON.stringify(content)}`,
      );
    }
    rule.headers.push([content.slice(0, colon).trim(), content.slice(colon + 1).trim()]);
  }
  return rules;
}

function pathPattern(path: string): RegExp {
  const source = path
    .split('*')
    .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('.*');
  return new RegExp(`^${source}$`);
}

/**
 * Headers for a request path, as Cloudflare applies them: every matching rule contributes, and a
 * header set by several rules gets their values joined with a comma. Keys are lower-case.
 */
export function headersForPath(
  rules: readonly HeaderRule[],
  pathname: string,
): Map<string, string> {
  const headers = new Map<string, string>();
  for (const rule of rules) {
    if (!pathPattern(rule.path).test(pathname)) continue;
    for (const [name, value] of rule.headers) {
      const key = name.toLowerCase();
      const previous = headers.get(key);
      headers.set(key, previous === undefined ? value : `${previous}, ${value}`);
    }
  }
  return headers;
}

/**
 * Writes `_headers` into every build (CSP `connect-src` from `VITE_STREAM_URL`) and makes
 * `vite preview` send the headers of the build it serves, so e2e fails on a CSP violation before
 * a deploy does. The dev server stays without them: Vite injects inline styles and scripts there.
 */
export function securityHeaders(): Plugin {
  let headersFile = '';
  let outDir = '';
  return {
    name: 'lsv:security-headers',
    configResolved(config) {
      const raw: unknown = config.env.VITE_STREAM_URL;
      const streamUrl = resolveStreamUrl(typeof raw === 'string' ? raw : undefined);
      headersFile = formatHeadersFile(securityHeaderRules(streamUrl));
      outDir = resolve(config.root, config.build.outDir);
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: HEADERS_FILE, source: headersFile });
    },
    configurePreviewServer(server) {
      // The built file, not this run's environment: preview must match what gets deployed.
      const file = resolve(outDir, HEADERS_FILE);
      let text: string;
      try {
        text = readFileSync(file, 'utf8');
      } catch (error) {
        throw new Error(`Cannot read ${file}; build the app first (pnpm build:local)`, {
          cause: error,
        });
      }
      const rules = parseHeadersFile(text);
      server.middlewares.use((req, res, next) => {
        const { pathname } = new URL(req.url ?? '/', 'http://preview.invalid');
        for (const [name, value] of headersForPath(rules, pathname)) res.setHeader(name, value);
        next();
      });
    },
  };
}
